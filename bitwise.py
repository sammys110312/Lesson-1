num = int(input("Enter a number: "))
not_result = -num
print("Not:", not_result)

num2 = int(input("Enter another number: "))
xor_result = num ^ num2
print("XOR:", xor_result)

left_result = num << 1
print("Left shift by one:", left_result)

right_result = num >> 1
print("Right shift by one:", right_result)